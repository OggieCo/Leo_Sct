#!/usr/bin/env python3
"""collision_tables_split.py — LaTeX tables for the two collision components.

Writes results/analysis/collision_split_tables.tex with two tables:

  * rover--human collisions per run
  * rover--rover collisions per run

Rows: all 14 layouts in density order (the two obstacle layouts below the rule).
Columns: Nav2, BT, BT+LLM (mean over the runs of that layout) and `n`, because
some BT+LLM cells still have fewer than ten runs.

The component counts are taken from the same BUMP stream as the total, so
human + rover may fall short of the total by the wall / obstacle / unattributed
contacts (documented in the collision-metric section).

  python3 scripts/collision_tables_split.py
"""

from __future__ import annotations

import csv
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve()
CSV = HERE.parents[2] / "results" / "analysis" / "run_metrics.csv"
OUT = HERE.parents[2] / "results" / "analysis" / "collision_split_tables.tex"

ARMS = (("no", "Nav2"), ("reactive", "BT"), ("ai", "BT+LLM"))
LABELS = {"bumps_human": ("Rover--human", "tab:res_coll_human"),
          "bumps_robot": ("Rover--rover", "tab:res_coll_robot")}


def order(scenario: str):
    if "obstacles" in scenario:
        return (1, int(scenario.split("_")[0]), 0)
    p = scenario.split("_")
    return (0, int(p[0]), int(p[2]))


def title(scenario: str) -> str:
    if "obstacles" in scenario:
        return f"{scenario.split('_')[0]} rovers, obstacles"
    p = scenario.split("_")
    r, h = int(p[0]), int(p[2])
    return f"{r} rovers, {h} human" + ("s" if h > 1 else "")


def main() -> int:
    rows = list(csv.DictReader(open(CSV, newline="")))
    data = defaultdict(lambda: defaultdict(list))
    for r in rows:
        data[r["scenario"]][r["arm"]].append(r)

    scenarios = sorted(data, key=order)
    out = ["% AUTO-GENERATED by scripts/collision_tables_split.py",
           "% Source: results/analysis/run_metrics.csv", ""]

    for metric, (label, ref) in LABELS.items():
        out += [
            "\\begin{table}[htbp]",
            "  \\centering",
            "  \\small",
            f"  \\caption{{{label} collisions per run: mean over the runs of each",
            f"  scenario ($n$), for the three configurations. The last two scenarios",
            f"  contain static obstacles and no pedestrians.}}",
            f"  \\label{{{ref}}}",
            f"  \\begin{{tabular}}{{lrrrrrr}}",
            "    \\toprule",
            f"    \\# & Scenario & \\multicolumn{{3}}{{c}}{{{label} collisions}} & "
            f"$n$ (Nav2/BT/BT+LLM) \\\\",
            "    \\cmidrule(lr){3-5}",
            "       &          & Nav2 & BT & BT+LLM & \\\\",
            "    \\midrule",
        ]
        i = 0
        prev_obst = False
        for scen in scenarios:
            obst = "obstacles" in scen
            if obst and not prev_obst:
                out.append("    \\midrule")
            prev_obst = obst
            i += 1
            means, ns = [], []
            for arm, _ in ARMS:
                rs = data[scen][arm]
                means.append(statistics.mean(float(r[metric]) for r in rs))
                ns.append(len(rs))
            n_txt = "/".join(str(x) for x in ns)
            out.append(f"    {i} & {title(scen):22s} & {means[0]:5.1f} & {means[1]:5.1f} "
                       f"& {means[2]:5.1f} & {n_txt} \\\\")
        out += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]

    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
