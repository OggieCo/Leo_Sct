#!/usr/bin/env python3
"""LaTeX table of collision counts per layout and configuration.

One table per configuration (Nav2, BT, BT+LLM), all 14 layouts as rows: the
whole-number collision count per run (total, then the rover--human /
rover--rover split) and the growth relative to the sparsest layout
(2 rovers, 1 human).  A closing row summarizes the exposure correlation.

Aggregate per cell defaults to the MEDIAN (robust for small integer counts);
use --stat mean when the split columns must add up exactly, since means are
additive and medians are not.  A collisions-per-100-m column is available with
--rate (unit: metres of fleet path per run).

  python3 scripts/collision_table.py                       # -> results/analysis/collision_table.tex
  python3 scripts/collision_table.py --stat mean --rate --out /tmp/t.tex
"""

from __future__ import annotations

import argparse
import csv
import math
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve()
DEFAULT_CSV = HERE.parents[2] / "results" / "analysis" / "run_metrics.csv"
DEFAULT_OUT = HERE.parents[2] / "results" / "analysis" / "collision_table.tex"

LONG = {"no": "Nav2 (stock)", "reactive": "BT (reactive)", "ai": "BT + LLM"}
LABELS = {"no": "tab:res_coll_medians_nav2",
          "reactive": "tab:res_coll_medians_bt",
          "ai": "tab:res_coll_medians_llm"}
BASE = "2_rovers_1_humans"          # sparsest layout: growth is measured from here


def order(scenario: str):
    """"4_rovers_2_humans" -> (0, 4, 2); obstacle layouts last, then by fleet
    size, so the density ladder reads top to bottom and the obstacle layouts
    sit together under the separating rule."""
    if "obstacles" in scenario:
        return (1, int(scenario.split("_")[0]), 0)
    p = scenario.split("_")
    return (0, int(p[0]), int(p[2]))


def title(scenario: str) -> str:
    if "obstacles" in scenario:
        return f"{scenario.split('_')[0]} rovers, obstacles"
    p = scenario.split("_")
    r, h = int(p[0]), int(p[2])
    return f"{r} rovers, {h} human" + ("s" if h > 1 else "")


def stat(vals, kind: str) -> float:
    return statistics.median(vals) if kind == "median" else statistics.mean(vals)


def whole(v: float) -> int:
    """Round half up to a whole collision (median of an even run count can be
    x.5; the caption states that the table is rounded)."""
    return int(math.floor(v + 0.5))


def agg(rows, col, kind: str) -> float:
    return stat([float(r[col]) for r in rows], kind)


def rate_100m(rows, kind: str) -> float:
    """Collisions per 100 m driven, computed per run before aggregating."""
    vals = []
    for r in rows:
        dist = float(r.get("path_total_m") or 0.0)
        if dist > 1.0:                       # ignore degenerate/partial runs
            vals.append(100.0 * float(r["bumps_total"]) / dist)
    return stat(vals, kind) if vals else float("nan")


def exposure_fit(rows):
    """-> (r, slope, R^2, n) for collisions per run vs. agents present.

    Obstacle layouts are excluded (there the dominant collision partner is static
    geometry rather than an agent)."""
    xs, ys = [], []
    for r in rows:
        if "obstacles" in r["scenario"]:
            continue
        p = r["scenario"].split("_")
        xs.append(int(p[0]) + int(p[2]))
        ys.append(float(r["bumps_total"]))
    if len(xs) < 3:
        return float("nan"), float("nan"), float("nan"), len(xs)
    mx, my = statistics.mean(xs), statistics.mean(ys)
    sxx = sum((x - mx) ** 2 for x in xs)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    r = sxy / (len(xs) * statistics.pstdev(xs) * statistics.pstdev(ys))
    return r, sxy / sxx, r * r, len(xs)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=str(DEFAULT_CSV))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--stat", choices=("median", "mean"), default="median",
                    help="aggregate per cell (mean is additive across the "
                         "human/rover split, median is not)")
    ap.add_argument("--rate", action="store_true",
                    help="also print collisions per 100 m driven")
    a = ap.parse_args()

    runs = list(csv.DictReader(open(a.csv, newline="")))
    data = defaultdict(lambda: defaultdict(list))
    for r in runs:
        data[r["scenario"]][r["arm"]].append(r)

    base = {arm: agg(data[BASE][arm], "bumps_total", a.stat)
            for arm in ("no", "reactive", "ai") if data[BASE].get(arm)}

    out = ["% AUTO-GENERATED by scripts/collision_table.py -- do not edit by hand.",
           "% Source: results/analysis/run_metrics.csv", ""]
    for arm in ("no", "reactive", "ai"):
        all_rows = [r for s in data for r in data[s].get(arm, [])]
        r_cor, slope, r2, n_cor = exposure_fit(all_rows)
        head = ["Layout", "Total", "Human / rover"]
        if a.rate:
            head.append("per 100\\,m")
        head.append("Growth")
        spec = "l" + "r" * (len(head) - 1)
        out += [
            "\\begin{table}[htbp]",
            "  \\centering",
            "  \\small",
            f"  \\caption{{Collisions per run, "
            f"{LONG[arm]} configuration: {a.stat} over the runs of each layout, "
            f"rounded to whole collisions, with the rover--human / "
            f"rover--rover split; growth is the {a.stat} total relative to the "
            f"{title(BASE)} layout. Layouts with static obstacles are listed "
            f"below the rule and are excluded from the correlation row.}}",
            f"  \\label{{{LABELS[arm]}}}",
            f"  \\begin{{tabular}}{{{spec}}}",
            "    \\toprule",
            "    " + " & ".join(head) + " \\\\",
            "    \\midrule",
        ]
        prev_obst = False
        for scenario in sorted(data, key=order):
            rows = data[scenario].get(arm)
            if not rows:
                continue
            is_obst = "obstacles" in scenario
            if is_obst and not prev_obst:
                out.append("    \\midrule")
            prev_obst = is_obst
            tot = agg(rows, "bumps_total", a.stat)
            hum = agg(rows, "bumps_human", a.stat)
            rov = agg(rows, "bumps_robot", a.stat)
            growth = tot / base[arm] if base[arm] else float("nan")
            cells = [title(scenario), f"{whole(tot)}",
                     f"{whole(hum)} / {whole(rov)}"]
            if a.rate:
                cells.append(f"{rate_100m(rows, a.stat):.2f}")
            cells.append(f"{growth:.1f}$\\times$")
            out.append("    " + " & ".join(cells) + " \\\\")
        out += [
            "    \\midrule",
            f"    \\multicolumn{{{len(head)}}}{{l}}{{\\emph{{Layouts without "
            f"obstacles: $r = {r_cor:.2f}$ between agents present and collisions "
            f"per run, slope $= {slope:+.2f}$ collisions per extra agent, "
            f"$R^{{2}} = {r2:.2f}$, $n = {n_cor}$ runs.}}}} \\\\",
            "    \\bottomrule",
            "  \\end{tabular}",
            "\\end{table}",
            "",
        ]

    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
